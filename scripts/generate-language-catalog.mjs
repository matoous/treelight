import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'packages/catalog/languages.json');
const generatedPath = path.join(root, 'packages/catalog/src/generated.ts');
const catalogPackagePath = path.join(root, 'packages/catalog/package.json');
const languageRoot = path.join(root, 'packages/languages');
const check = process.argv.includes('--check');
const GENERATED_HEADER = `// Generated by scripts/generate-language-catalog.mjs.
// Edit packages/catalog/languages.json and regenerate instead.`;

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const catalogPackage = JSON.parse(await readFile(catalogPackagePath, 'utf8'));
const errors = [];
const packageDirectories = new Map();

for (const directory of await readdir(languageRoot, { withFileTypes: true })) {
  if (!directory.isDirectory()) continue;
  const packagePath = path.join(languageRoot, directory.name, 'package.json');
  const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
  packageDirectories.set(packageJson.name, {
    directory: path.join(languageRoot, directory.name),
    packageJson,
  });
}

const catalogPackages = new Set(
  manifest.languages.map((entry) => entry.package),
);
const grammarPackages = new Set(
  [...packageDirectories]
    .filter(([, value]) => value.packageJson.treelightLanguage?.artifact)
    .map(([packageName]) => packageName),
);

for (const packageName of grammarPackages) {
  if (!catalogPackages.has(packageName)) {
    errors.push(
      `Grammar package ${packageName} is missing from languages.json.`,
    );
  }
}
for (const packageName of catalogPackages) {
  if (!grammarPackages.has(packageName)) {
    errors.push(
      `Catalog package ${packageName} does not contain a grammar artifact.`,
    );
  }
}

const names = new Map();
const extensions = new Map();
const filenames = new Map();
const normalizedEntries = manifest.languages.map((entry) => ({
  id: entry.id,
  package: entry.package,
  aliases: entry.aliases ?? [],
  extensions: entry.extensions ?? [],
  filenames: entry.filenames ?? [],
  filenamePrefixes: entry.filenamePrefixes ?? [],
}));

function addUnique(map, value, entryId, kind) {
  const normalized = normalize(value);
  const existing = map.get(normalized);
  if (existing && existing !== entryId) {
    errors.push(`${kind} ${value} is shared by ${existing} and ${entryId}.`);
  } else {
    map.set(normalized, entryId);
  }
}

for (const entry of normalizedEntries) {
  for (const name of [entry.id, ...entry.aliases, ...entry.extensions]) {
    addUnique(names, name, entry.id, 'Language name');
  }
  for (const extension of entry.extensions) {
    addUnique(extensions, extension, entry.id, 'File extension');
  }
  for (const filename of entry.filenames) {
    addUnique(filenames, filename, entry.id, 'Filename');
  }

  const languagePackage = packageDirectories.get(entry.package);
  if (!languagePackage) continue;

  const dependencyVersion = catalogPackage.dependencies?.[entry.package];
  if (dependencyVersion !== languagePackage.packageJson.version) {
    errors.push(
      `${entry.package} must be a catalog dependency at version ${languagePackage.packageJson.version}.`,
    );
  }

  const metadata = languagePackage.packageJson.treelightLanguage;
  const artifactPath = path.join(
    languagePackage.directory,
    'src/wasm',
    metadata.artifact,
  );
  await assertReadable(artifactPath, `${entry.package} grammar artifact`);
  if ((metadata.queries?.highlights?.length ?? 0) === 0) {
    errors.push(`${entry.package} does not declare a highlight query.`);
  }
  await assertReadable(
    path.join(languagePackage.directory, 'src/queries/highlights.scm'),
    `${entry.package} highlight query`,
  );
}

const knownInjectionLanguages = new Set(names.keys());
const injectionPattern = /#set!\s+injection\.language\s+"([^"]+)"/g;

for (const { directory, packageJson } of packageDirectories.values()) {
  const queryDirectory = path.join(directory, 'src/queries');
  let queryFiles = [];
  try {
    queryFiles = (await readdir(queryDirectory)).filter((file) =>
      file.endsWith('.scm'),
    );
  } catch {
    continue;
  }
  for (const queryFile of queryFiles) {
    const query = await readFile(path.join(queryDirectory, queryFile), 'utf8');
    for (const match of query.matchAll(injectionPattern)) {
      if (!knownInjectionLanguages.has(normalize(match[1]))) {
        errors.push(
          `${packageJson.name} injects unknown static language ${match[1]}.`,
        );
      }
    }
  }
}

if (errors.length > 0) {
  throw new Error(`Invalid language catalog:\n- ${errors.join('\n- ')}`);
}

const source = `${GENERATED_HEADER}
import type { LanguageCatalogEntry } from './types.js';

export const languageCatalog = [
${normalizedEntries.map(renderEntry).join('\n')}
] satisfies readonly LanguageCatalogEntry[];
`;

if (check) {
  let current = '';
  try {
    current = await readFile(generatedPath, 'utf8');
  } catch {
    // The comparison below reports the actionable error.
  }
  if (current !== source) {
    throw new Error(
      'Language catalog is out of date. Run `npm run generate:catalog`.',
    );
  }
} else {
  await writeFile(generatedPath, source);
}

function renderEntry(entry) {
  return `  {
    id: ${renderString(entry.id)},
    packageName: ${renderString(entry.package)},
    aliases: ${renderArray(entry.aliases)},
    extensions: ${renderArray(entry.extensions)},
    filenames: ${renderArray(entry.filenames)},
    filenamePrefixes: ${renderArray(entry.filenamePrefixes)},
    loader: () => import(${renderString(entry.package)}),
  },`;
}

function normalize(value) {
  return value.trim().toLowerCase().replaceAll('_', '-');
}

function renderArray(values) {
  return `[${values.map(renderString).join(', ')}]`;
}

function renderString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

async function assertReadable(file, label) {
  try {
    await readFile(file);
  } catch {
    errors.push(`${label} is missing at ${path.relative(root, file)}.`);
  }
}
